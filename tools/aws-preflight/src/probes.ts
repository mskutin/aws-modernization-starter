function deepFreeze<T>(value: T): T {
  if (typeof value === 'object' && value !== null && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

/** One definition for `workload`: the region token replaced, duplicates (us-east-1) dropped. */
function forRegion(def: ProbeDef, workload: string): ProbeDef {
  const sub = (t: string) => t.replaceAll(WORKLOAD_REGION, workload);
  return {
    ...def,
    regions: [...new Set(def.regions.map(sub))],
    args: def.args.map(sub),
    ...(def.iamResources ? { iamResources: [...new Set(def.iamResources.map(sub))] } : {}),
  };
}

export interface ProbeCatalogue {
  readonly workloadRegion: string;
  /** The allowlist (deep-frozen). */
  readonly probes: readonly ProbeDef[];
  readonly byId: ReadonlyMap<string, ProbeDef>;
}

const CATALOGUES = new Map<string, ProbeCatalogue>();

/**
 * The validated, deep-frozen allowlist for a workload region (cached). Throws for a region that is
 * not an aws-partition region (`assertValidRegistry`), so no catalogue exists for one.
 */
export function probesFor(workload: string): ProbeCatalogue {
  const cached = CATALOGUES.get(workload);
  if (cached) return cached;
  const defs = DEFS.map((d) => forRegion(d, workload));
  assertValidRegistry(defs, workload);
  const probes: readonly ProbeDef[] = deepFreeze(defs);
  const catalogue: ProbeCatalogue = Object.freeze({
    workloadRegion: workload,
    probes,
    byId: new Map(probes.map((p) => [p.id, p])),
  });
  CATALOGUES.set(workload, catalogue);
  return catalogue;
}

/** The allowlist of the default workload region (validated when this module loads). */
export const PROBES: readonly ProbeDef[] = probesFor(DEFAULT_WORKLOAD_REGION).probes;
export const PROBES_BY_ID: ReadonlyMap<string, ProbeDef> = probesFor(DEFAULT_WORKLOAD_REGION).byId;
