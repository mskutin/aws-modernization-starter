/** Builds Guard unit-test documents (`cfn-guard test` YAML) from the rule fixtures. */
import { ruleById } from '../src/catalogue.js';
import { guardFileFor } from '../src/guard/layout.js';
import { guardRuleName } from '../src/types.js';
import { RULE_CASES, templateOf, type GuardStatus, type Resources } from './fixtures/cases.js';

export interface GuardTestCase {
  name: string;
  input: ReturnType<typeof templateOf>;
  expectations: { rules: Record<string, GuardStatus> };
}

const entry = (
  ruleId: string,
  name: string,
  resources: Resources,
  status: GuardStatus,
): GuardTestCase => ({
  name: `${ruleId}: ${name}`,
  input: templateOf(resources),
  expectations: { rules: { [guardRuleName(ruleId)]: status } },
});

/** Map of guard file name (e.g. `s3`) → ordered test cases. */
export function buildGuardTests(): Map<string, GuardTestCase[]> {
  const byFile = new Map<string, GuardTestCase[]>();
  for (const c of RULE_CASES) {
    if (!ruleById(c.ruleId)?.engines.includes('guard')) continue;
    const file = guardFileFor(c.ruleId);
    const list = byFile.get(file) ?? [];
    list.push(entry(c.ruleId, 'passing fixture', c.pass, c.guardPass ?? 'PASS'));
    list.push(entry(c.ruleId, 'failing fixture', c.fail, 'FAIL'));
    for (const v of c.variants ?? [])
      list.push(entry(c.ruleId, `variant - ${v.name}`, v.resources, v.guard));
    byFile.set(file, list);
  }
  return byFile;
}

