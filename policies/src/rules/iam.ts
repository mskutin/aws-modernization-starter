export const ADMIN_MANAGED_POLICIES = ['AdministratorAccess', 'PowerUserAccess', 'IAMFullAccess'];

const FULL_OR_SERVICE_WILDCARD = /^(\*|[A-Za-z0-9-]+:\*)$/;

export interface StatementRef {
  statement: Record<string, unknown>;
  path: string;
}

/** Identity-based policy statements of IAM resources (resource policies are out of scope). */
export function identityStatements(r: CfnResourceJson): StatementRef[] {
  const p = props(r);
  const docs: { doc: unknown; path: string }[] = [];
  if (r.Type === 'AWS::IAM::Policy' || r.Type === 'AWS::IAM::ManagedPolicy') {
    docs.push({ doc: p['PolicyDocument'], path: 'Properties/PolicyDocument' });
  }
  if (['AWS::IAM::Role', 'AWS::IAM::User', 'AWS::IAM::Group'].includes(r.Type)) {
    asArray(p['Policies']).forEach((pol, i) =>
      docs.push({
        doc: get(pol, 'PolicyDocument'),
        path: `Properties/Policies/${i}/PolicyDocument`,
      }),
    );
  }
  return docs.flatMap(({ doc, path }) =>
    asArray(get(doc, 'Statement')).flatMap((s, i) =>
      isRecord(s) ? [{ statement: s, path: `${path}/Statement/${i}` }] : [],
    ),
  );
}

const IDENTITY_TYPES = [
  'AWS::IAM::Policy',
  'AWS::IAM::ManagedPolicy',
  'AWS::IAM::Role',
  'AWS::IAM::User',
  'AWS::IAM::Group',
];

const isAllow = (s: Record<string, unknown>) => s['Effect'] === 'Allow';

/** BASE-IAM-006: a trust policy rejects NotPrincipal in every statement. */
const TRUST_POLICY = { subject: 'Trust policy', notPrincipal: 'any' } as const;

const hasStarResource = (s: Record<string, unknown>) =>
  asArray(s['Resource']).some((r) => r === '*');

